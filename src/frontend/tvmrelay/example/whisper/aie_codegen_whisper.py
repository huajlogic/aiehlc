"""``relay.ext.aie_whisper``: one C wrapper per AIE layer.

TVM calls this for every function ``aie_partition`` cut out (attribute
``Compiler="aie_whisper"``). The wrapper has TVM's packed-call ABI, so the
graph executor calls it exactly like one of its own kernels, and does three
things -- the same three on the board and in the x86 emulation, because the
library behind ``aiew_<sig>_port/_run`` is the only thing that differs:

1. **stage** each input into the library's DMA buffer through the layer's
   strided view (``PortView``): this is where the layout ops the partitioner
   absorbed (head split/merge, transposes, broadcast of a mask) and the
   padding to the tile grid happen -- data movement only, no arithmetic.
   GEMMs additionally get the bias column (``A[:,K]=1``, ``B[:,K]=bias``) and
   conv1d its im2col;
2. **run** the library (one launch; a batched matmul launches once per batch);
3. **collect** the result back into TVM's output tensor through the output
   view (gather or scatter).

Descriptors come from ``LAYERS`` (filled by the flow before ``relay.build``),
keyed by the function's ``global_symbol``.
"""

from __future__ import annotations

LAYERS: dict = {}

PRELUDE = r"""
/* Generated by src/frontend/tvmrelay/example/whisper/aie_codegen_whisper.py -- do not edit. */
#include <stdint.h>
#include <stdlib.h>
#include <string.h>
#ifndef TVM_DLL
#define TVM_DLL
#endif
#ifndef WSP_PRELUDE
#define WSP_PRELUDE
/* TVMValue[i].v_handle is a DLTensor*, whose first field is `void *data`. */
#define WSP_ARG(args, i) (*(void **)(((void **)(args))[i]))

/* dst[row-major over shape, last dim pitched] = src[sum idx*stride] */
static void wsp_gather(float *dst, long pitch, const float *src, int rank,
                       const long *shape, const long *stride) {
    long idx[8] = {0}, n = 1, last = shape[rank - 1];
    for (int d = 0; d < rank; d++) n *= shape[d];
    for (long f = 0; f < n; f++) {
        long off = 0;
        for (int d = 0; d < rank; d++) off += idx[d] * stride[d];
        dst[(f / last) * pitch + f % last] = src[off];
        for (int d = rank - 1; d >= 0; d--) { if (++idx[d] < shape[d]) break; idx[d] = 0; }
    }
}
/* dst[sum idx*stride] = src[row-major over shape, last dim pitched] */
static void wsp_scatter(float *dst, const float *src, long pitch, int rank,
                        const long *shape, const long *stride) {
    long idx[8] = {0}, n = 1, last = shape[rank - 1];
    for (int d = 0; d < rank; d++) n *= shape[d];
    for (long f = 0; f < n; f++) {
        long off = 0;
        for (int d = 0; d < rank; d++) off += idx[d] * stride[d];
        dst[off] = src[(f / last) * pitch + f % last];
        for (int d = rank - 1; d >= 0; d--) { if (++idx[d] < shape[d]) break; idx[d] = 0; }
    }
}
#endif
"""


def _arr(vals):
    return "{" + ", ".join(f"{int(v)}L" for v in vals) + "}"


def _view_decl(name, view, drop_batch=False):
    shape, stride = list(view.shape), list(view.strides)
    if drop_batch:
        shape, stride = shape[1:], stride[1:]
    return (f"    static const long {name}_shape[] = {_arr(shape)};\n"
            f"    static const long {name}_stride[] = {_arr(stride)};\n")


def _collect(L, src, pitch):
    """Graph output <- logical result held in ``src`` (row pitch ``pitch``)."""
    v = L.out_view
    s = _view_decl("o", v)
    if v.scatter:
        return s + f"    wsp_scatter(out, {src}, {pitch}, {len(v.shape)}, o_shape, o_stride);\n"
    if pitch != v.shape[-1] and src != "V":
        raise ValueError("gather output needs a contiguous logical result")
    return s + f"    wsp_gather(out, {v.shape[-1]}, {src}, {len(v.shape)}, o_shape, o_stride);\n"


def emit_gemm(L) -> str:
    lib, sig = L.lib, L.lib["sig"]
    Kp, Np = lib["K"], lib["N"]
    batch = L.batch
    body = [f"    float *A = {sig}_port(0), *B = {sig}_port(1), *C = {sig}_port(2);",
            "    if (!A || !B || !C) return -1;"]
    body.append(f"    static float *V = 0;\n    if (!V) V = (float *)malloc({batch * L.M * L.N}u * sizeof(float));"
                "\n    if (!V) return -2;")
    if L.op == "conv1d":
        c = L.conv
        body.append(f"""    const float *x = (const float *)WSP_ARG(args, {c['x_arg']});
    const float *w = (const float *)WSP_ARG(args, {c['w_arg']});
    /* im2col: A[t, ci*{c['ksize']}+k] = x[ci, t*{c['stride']}+k-{c['pad']}] (0 outside) */
    for (long t = 0; t < {L.M}; t++)
        for (long ci = 0; ci < {c['cin']}; ci++)
            for (long k = 0; k < {c['ksize']}; k++) {{
                long ti = t * {c['stride']} + k - {c['pad']};
                A[t * {Kp} + ci * {c['ksize']} + k] = (ti >= 0 && ti < {c['t_in']}) ? x[ci * {c['t_in']} + ti] : 0.0f;
            }}
    /* weight [co, ci, k] is already B[co, ci*k] row-major */
    for (long n = 0; n < {L.N}; n++)
        memcpy(B + n * {Kp}, w + n * {L.K}, {L.K}u * sizeof(float));""")
    body.append("    for (long b = 0; b < %d; b++) {" % batch)
    if L.op != "conv1d":
        a, bv = L.a_view, L.b_view
        db = batch > 1
        body.append(_view_decl("a", a, db) + _view_decl("bb", bv, db))
        boff_a = f" + b * {a.strides[0]}" if db else ""
        boff_b = f" + b * {bv.strides[0]}" if db else ""
        body.append(f"        wsp_gather(A, {Kp}, (const float *)WSP_ARG(args, {a.arg}){boff_a}, "
                    f"{2}, a_shape, a_stride);")
        body.append(f"        wsp_gather(B, {Kp}, (const float *)WSP_ARG(args, {bv.arg}){boff_b}, "
                    f"{2}, bb_shape, bb_stride);")
    if L.bias_arg >= 0:
        body.append(f"""        {{ /* bias as an extra K column: A[:,K] = 1, B[:,K] = bias */
            const float *bias = (const float *)WSP_ARG(args, {L.bias_arg});
            for (long m = 0; m < {L.M}; m++) A[m * {Kp} + {L.K}] = 1.0f;
            for (long n = 0; n < {L.N}; n++) B[n * {Kp} + {L.K}] = bias[n];
        }}""")
    body.append(f"""        int rc = {sig}_run();
        if (rc != 0) return rc;
        for (long m = 0; m < {L.M}; m++)
            memcpy(V + (b * {L.M} + m) * {L.N}, C + m * {Np}, {L.N}u * sizeof(float));
    }}""")
    body.append(_collect(L, "V", L.N))
    return "\n".join(body)


def emit_row(L) -> str:
    lib, sig = L.lib, L.lib["sig"]
    cols = L.cols
    body = [f"    float *A = {sig}_port(0), *C = {sig}_port(2);", "    if (!A || !C) return -1;"]
    if L.op == "embed":
        c = L.conv
        body.append(f"""    {{ /* gather: the DMA would fetch table rows at token-dependent addresses */
        const float *table = (const float *)WSP_ARG(args, {c['table_arg']});
        const int64_t *tok = (const int64_t *)WSP_ARG(args, {c['tokens_arg']});
        for (long r = 0; r < {L.rows}; r++) {{
            int64_t t = tok[r];
            if (t < 0) t += {c['vocab']};
            memcpy(A + r * {cols}, table + t * {cols}, {cols}u * sizeof(float));
        }}
    }}""")
    else:
        v = L.row_views[0]
        body.append(_view_decl("a", v) +
                    f"    wsp_gather(A, {v.shape[-1]}, (const float *)WSP_ARG(args, {v.arg}), "
                    f"{len(v.shape)}, a_shape, a_stride);")
    if lib["op"] == "layernorm":
        g, b = L.params
        body.append(f"""    float *P = {sig}_port(1);
    if (!P) return -1;
    memcpy(P, WSP_ARG(args, {g}), {cols}u * sizeof(float));
    memcpy(P + {cols}, WSP_ARG(args, {b}), {cols}u * sizeof(float));""")
    elif lib["ports"] == 3:
        v = L.row_views[1]
        body.append(f"    float *Bp = {sig}_port(1);\n    if (!Bp) return -1;\n" + _view_decl("bb", v) +
                    f"    wsp_gather(Bp, {v.shape[-1]}, (const float *)WSP_ARG(args, {v.arg}), "
                    f"{len(v.shape)}, bb_shape, bb_stride);")
    body.append(f"    int rc = {sig}_run();\n    if (rc != 0) return rc;")
    body.append(_collect(L, "C", cols))
    return "\n".join(body)


def emit_layer(L) -> str:
    sig = L.lib["sig"]
    n_in = len(L.arg_shapes)
    kind = emit_gemm(L) if L.lib["template"] == "gemm" else emit_row(L)
    return f"""
#ifdef __cplusplus
extern "C" {{
#endif
float *{sig}_port(int i);
int {sig}_run(void);
/* {L.symbol}: {L.graph} layer {L.index:03d}, {L.describe()}
 *   relay ops : {' '.join(L.relay_ops)}
 *   args      : {', '.join(f'{r}{list(s)}' for r, s in zip(L.arg_roles, L.arg_shapes))}
 *   output    : {list(L.out_shape)}
 *   aiehlc lib: lib{sig}.a */
TVM_DLL int32_t {L.symbol}(void *args, int32_t *type_codes, int32_t num_args,
                           void *out_ret_value, int32_t *out_ret_tcode, void *resource_handle) {{
    (void)type_codes; (void)out_ret_value; (void)out_ret_tcode; (void)resource_handle;
    if (num_args != {n_in + 1}) return -100;
    float *out = (float *)WSP_ARG(args, {n_in});
{kind}
    return 0;
}}
#ifdef __cplusplus
}}
#endif
"""


def _register():
    import tvm
    from tvm import relay

    @tvm._ffi.register_func("relay.ext.aie_whisper", override=True)
    def aie_whisper_compiler(ref):
        if not isinstance(ref, relay.Function):
            raise ValueError(f"relay.ext.aie_whisper expected a Function, got {type(ref)}")
        name = str(ref.attrs["global_symbol"])
        if name not in LAYERS:
            raise KeyError(f"{name}: no AIE layer descriptor (partition not run in this process?)")
        code = PRELUDE + emit_layer(LAYERS[name])
        return tvm.get_global_func("runtime.CSourceModuleCreate")(code, "c", [name], [])

    return aie_whisper_compiler


def register():
    return _register()
