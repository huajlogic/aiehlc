"""Stage 8: link the baremetal aarch64 ELF -- compile level only, never run here.

Pieces, all generated or built by earlier stages:

* ``whisper_<graph>_driver.c`` -- a static graph executor generated from TVM's
  graph JSON: one storage arena, parameters pointing into the linked weight
  blob (offsets from ``arm_build.param_offsets``), and one call per node in
  graph order. There is no TVM runtime on the board; every call is to an AIE
  layer wrapper (``__nop`` reshapes become an alias or a memcpy).
* the wrappers TVM's BYOC codegen produced (``relay.ext.aie_whisper``), from
  the ``target="c"`` build -- the same C the x86 verification compiled;
* ``main.c`` -- encoder on the embedded JFK log-mel, then one decoder step on
  the start-of-transcript prompt; prints the first token;
* every ``lib<sig>.a`` aiehlc archived. Each library's ``host.o`` defines the
  same pipeline symbols (``host_canonicalized``, ...), so before linking
  everything but ``<sig>_port``/``<sig>_run`` and the embedded core-ELF
  symbols is made local (``objcopy --keep-global-symbol``), on a copy.

The link is the check: unresolved symbols, duplicate definitions and a memory
map that does not fit fail here, at compile time.
"""

from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[5]

_DL = r"""
/* What a layer wrapper reads of a DLTensor: the leading data pointer. The rest
 * of the struct is laid out as dlpack's so a real TVM runtime could share it. */
typedef struct {
    void *data;
    int32_t device_type, device_id;
    int32_t ndim;
    uint8_t code, bits;
    uint16_t lanes;
    int64_t *shape, *strides;
    uint64_t byte_offset;
} wsp_dltensor;
"""


def generate_driver(graph_json: Path, params_blob: Path, name: str, out: Path) -> dict:
    """C source for a static executor of ``graph_json``. Returns a summary."""
    from frontend.tvmrelay.arm_build import param_offsets

    g = json.loads(graph_json.read_text())
    nodes, rp = g["nodes"], g["node_row_ptr"]
    sids, shapes, dtypes = g["attrs"]["storage_id"][1], g["attrs"]["shape"][1], g["attrs"]["dltype"][1]
    offs = param_offsets(params_blob)
    nbytes = lambda e: int(np.prod(shapes[e])) * (np.dtype(dtypes[e]).itemsize)
    sid_size = {}
    for e, s in enumerate(sids):
        sid_size[s] = max(sid_size.get(s, 0), nbytes(e))
    inputs = [i for i in g["arg_nodes"] if nodes[i]["name"] not in offs]
    sid_off, total = {}, 0
    param_sids = {sids[rp[i]] for i in g["arg_nodes"] if nodes[i]["name"] in offs}
    for s in sorted(sid_size):
        if s in param_sids:
            continue
        sid_off[s] = total
        total += (sid_size[s] + 63) // 64 * 64
    L = [f"/* Generated by whisper_board.py from {graph_json.name} -- do not edit. */",
         "#include <stdint.h>", "#include <stdlib.h>", "#include <string.h>", _DL,
         f"static wsp_dltensor T[{len(sids)}];",
         f"static uint8_t *arena;", ""]
    calls, decls = [], set()
    for i, n in enumerate(nodes):
        if n["op"] != "tvm_op":
            continue
        fn = n["attrs"]["func_name"]
        ins = [rp[a[0]] + a[1] for a in n["inputs"]]
        outs = [rp[i] + k for k in range(int(n["attrs"]["num_outputs"]))]
        if fn == "__nop":
            if sids[ins[0]] != sids[outs[0]]:
                calls.append(f"    memcpy(T[{outs[0]}].data, T[{ins[0]}].data, {nbytes(outs[0])}u);")
            continue
        decls.add(fn)
        args = ", ".join(f"&T[{e}]" for e in ins + outs)
        calls.append(f"    {{ void *a[] = {{{args}}}; rc = {fn}(a, 0, {len(ins) + len(outs)}, 0, 0, 0);"
                     f" if (rc) return rc; }}")
    for fn in sorted(decls):
        L.append(f"int32_t {fn}(void *, int32_t *, int32_t, void *, int32_t *, void *);")
    L += ["", f"int whisper_{name}_init(const uint8_t *blob) {{",
          f"    if (!arena) arena = (uint8_t *)malloc({total}u);",
          "    if (!arena) return -1;"]
    for e in range(len(sids)):
        node = next(i for i in range(len(nodes)) if rp[i] <= e < rp[i + 1])
        nm = nodes[node]["name"]
        if nodes[node]["op"] == "null" and nm in offs:
            L.append(f"    T[{e}].data = (void *)(blob + {offs[nm][0]}u); /* {nm} */")
        else:
            L.append(f"    T[{e}].data = arena + {sid_off[sids[e]]}u;")
    L += ["    return 0;", "}", "",
          f"void *whisper_{name}_input(int i) {{"]
    L += [f"    if (i == {k}) return T[{rp[n]}].data; /* {nodes[n]['name']} */" for k, n in enumerate(inputs)]
    L += ["    return 0;", "}", "",
          f"void *whisper_{name}_output(void) {{ return T[{rp[g['heads'][0][0]] + g['heads'][0][1]}].data; }}",
          "", f"int whisper_{name}_run(void) {{", "    int rc = 0;"] + calls + ["    return rc;", "}", ""]
    out.write_text("\n".join(L))
    return {"calls": len(calls), "aie_layers": len(decls), "arena_bytes": total,
            "inputs": [nodes[n]["name"] for n in inputs]}


_MAIN = r"""/* Generated by whisper_board.py -- Whisper-tiny on the AIE, baremetal entry. */
#include <stdint.h>
#include <stdio.h>
#include <string.h>
extern const uint8_t _binary_encoder_params_bin_start[];
extern const uint8_t _binary_decoder_params_bin_start[];
extern const uint8_t _binary_jfk_mel_bin_start[];
int whisper_encoder_init(const uint8_t *); void *whisper_encoder_input(int);
int whisper_encoder_run(void); void *whisper_encoder_output(void);
int whisper_decoder_init(const uint8_t *); void *whisper_decoder_input(int);
int whisper_decoder_run(void); void *whisper_decoder_output(void);
int main(void) {
    printf("whisper-aie: init\n");
    if (whisper_encoder_init(_binary_encoder_params_bin_start) ||
        whisper_decoder_init(_binary_decoder_params_bin_start)) return 1;
    memcpy(whisper_encoder_input(0), _binary_jfk_mel_bin_start, %(mel_bytes)du);
    printf("whisper-aie: encoder (%(enc)d AIE layers)\n");
    if (whisper_encoder_run()) return 2;
    int64_t *tok = (int64_t *)whisper_decoder_input(0);
    const int64_t prompt[4] = {%(prompt)s};
    for (int i = 0; i < %(T)d; i++) tok[i] = i < 4 ? prompt[i] : %(eot)d;
    memcpy(whisper_decoder_input(1), whisper_encoder_output(), %(feat_bytes)du);
    printf("whisper-aie: decoder step (%(dec)d AIE layers)\n");
    if (whisper_decoder_run()) return 3;
    const float *lg = (const float *)whisper_decoder_output() + 3 * %(V)d;
    int best = 0;
    for (int v = 1; v < %(V)d; v++) if (lg[v] > lg[best]) best = v;
    printf("whisper-aie: first token %%d\n", best);
    return 0;
}
"""


def _tool(name):
    t = shutil.which(name)
    if not t:
        raise RuntimeError(f"{name} not on PATH (source script/setup.sh --path-set-only)")
    return t


def localize_archive(arch: Path, keep: list, out: Path) -> Path:
    """Copy of ``arch`` whose ``host.o`` exports only ``keep`` (+ core-ELF symbols)."""
    work = out.parent / (out.stem + "_x")
    shutil.rmtree(work, ignore_errors=True)
    work.mkdir(parents=True)
    ar, objcopy = _tool("aarch64-none-elf-ar"), _tool("aarch64-none-elf-objcopy")
    arch = Path(arch).resolve()
    subprocess.run([ar, "x", str(arch)], cwd=work, check=True)
    flags = [f"--keep-global-symbol={s}" for s in keep]
    subprocess.run([objcopy] + flags + ["host.o"], cwd=work, check=True)
    shutil.copy(arch, out)
    subprocess.run([ar, "r", str(out), "host.o"], cwd=work, check=True)
    shutil.rmtree(work)
    return out


def link(out_dir: Path, wrapper_sources: list, drivers: list, blobs: dict, archives: dict,
         dims: dict, verbose: bool = True) -> dict:
    out_dir.mkdir(parents=True, exist_ok=True)
    gcc = _tool("aarch64-none-elf-gcc")
    ld = _tool("aarch64-none-elf-ld")
    bsp = REPO / "thirdparty/arch/cortexa78_0/workspace/platform_baremetal/cortexa78_0/standalone_cortexa78_0/bsp"
    alib = REPO / "thirdparty/alib/lib"
    (out_dir / "main.c").write_text(_MAIN % dims)
    objs = []
    for src in list(wrapper_sources) + list(drivers) + [out_dir / "main.c"]:
        o = out_dir / (Path(src).stem + ".o")
        subprocess.run([gcc, "-O2", "-mcpu=cortex-a78", "-c", str(src), "-o", str(o),
                        "-I", str(bsp / "include")], check=True)
        objs.append(str(o))
    for name, path in blobs.items():
        local = out_dir / f"{name}.bin"
        if not local.exists() or local.stat().st_size != Path(path).stat().st_size:
            shutil.copy(path, local)
        o = out_dir / f"{name}_bin.o"
        subprocess.run([ld, "-r", "-b", "binary", "-o", str(o), local.name], cwd=out_dir, check=True)
        objs.append(str(o))
    libs = []
    for sig, (arch, kernel) in archives.items():
        libs.append(str(localize_archive(Path(arch), [f"{sig}_port", f"{sig}_run"],
                                         out_dir / "libs" / f"lib{sig}.a")))
    elf = out_dir / "whisper_aie.elf"
    cmd = ([gcc, "-O2", "-mcpu=cortex-a78", "-o", str(elf)] + objs +
           ["-Wl,--start-group"] + libs + ["-Wl,--end-group",
            "--specs=nosys.specs", "-Wl,--defsym,end=__bss_end__",
            "-Wl,-T", "-Wl," + str(REPO / "thirdparty/arch/cortexa78_0/lscript.ld"),
            "-L" + str(alib), "-L" + str(bsp / "lib"),
            "-L" + str(bsp / "lib/../libsrc/build_configs/gen_bsp/libsrc/aienginev2/src"),
            "-Wl,--start-group,-lm,-lxaienginea78,-lxil,-lgcc,-lc,-lstdc++,-lxiltimer,"
            "-lxilstandalone,-lxilpm_ng,--end-group"])
    proc = subprocess.run(cmd, capture_output=True, text=True)
    res = {"elf": str(elf), "ok": proc.returncode == 0 and elf.is_file(),
           "libraries": len(libs), "objects": len(objs)}
    if not res["ok"]:
        res["error"] = proc.stderr[-4000:]
    else:
        res["bytes"] = elf.stat().st_size
        nm = subprocess.run([_tool("aarch64-none-elf-nm"), str(elf)], capture_output=True, text=True).stdout
        res["embedded_core_elfs"] = sum(1 for ln in nm.splitlines() if ln.endswith("_start")
                                        and "_binary_kernel_" in ln)
    if verbose:
        if res["ok"]:
            print(f"  [board] {elf.name}: {res['bytes']:,} B, {res['libraries']} aiehlc libraries, "
                  f"{res['embedded_core_elfs']} embedded AIE core ELFs (linked, not run)")
        else:
            print(f"  [board] LINK FAILED:\n{res['error'][-1500:]}")
    return res
