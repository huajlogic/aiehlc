"""x86 emulation of an aiehlc library: the RESOLVED core kernel, on the host.

No hardware and no AIE simulator: what this runs is the kernel source aiehlc
wrote after resolving every ``aie::get_*`` builtin
(``aout/worklocal/<kernel>.cc``), compiled with the host compiler, with the
window API (``acquire_/release_input_window`` ...) implemented by a feeder
that models the data distribution the spatial spaces declare:

``gemm`` (GemmSpace, R x C mesh, fullconnect_auto=1)
    tile (r, c) owns rows ``r*M/R ..`` of A and C and rows ``c*N/C ..`` of B;
    iteration ``it`` of ``m_rounds*n_rounds`` pairs A sub-tile ``it / n_rounds``
    with B sub-tile ``it % n_rounds`` ("A repeats while B cycles"), each over
    ``k_rounds`` K chunks; one C window per iteration.
``row`` (RowSpace, 1 x R mesh)
    tile r (mesh column r) owns rows ``r*rows/R ..`` of every Row port, streamed in whole-row
    windows; a Col port (layer-norm gamma/beta) is streamed whole to every tile.

What this establishes: the kernel body aiehlc emits, with the constants aiehlc
resolved, computes the layer -- and consumes exactly the number of windows the
plan says the DMA will deliver (counted per port per tile; a mismatch is a hang
on hardware and an error here). What it does NOT establish: that the shim and
tile BDs aiehlc generated move those bytes in that order. The GEMM result is
independent of which (m, n) sub-tile a tile computes first, so the emulation is
not sensitive to that choice; the BD programming itself still needs a board or
aiesim.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

from aie_kernels_whisper import TILE_M, TILE_N, port_elems

_HARNESS = r"""
/* x86 emulation of {sig} -- generated by aie_emu_whisper.py */
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <vector>
struct WspPort {{
    int r, c;
    long count;
    std::vector<float> buf;
    void (*fill)(WspPort *, long, float *);
    void (*drain)(WspPort *, long, const float *);
}};
struct input_window_int32 {{ WspPort *p; }};
struct output_window_int32 {{ WspPort *p; }};
static void *acquire_input_window(input_window_int32 *w) {{
    w->p->fill(w->p, w->p->count, w->p->buf.data());
    return w->p->buf.data();
}}
static void release_input_window(input_window_int32 *w) {{ w->p->count++; }}
static void *acquire_output_window(output_window_int32 *w) {{ return w->p->buf.data(); }}
static void release_output_window(output_window_int32 *w) {{
    w->p->drain(w->p, w->p->count, w->p->buf.data());
    w->p->count++;
}}

/* ---- resolved kernel, verbatim from aiehlc ({kernel_file}) ---- */
{kernel}
/* ---- end resolved kernel ---- */

static float *g_port[3];
extern "C" float *{sig}_port(int i) {{
    static const long elems[3] = {{{e0}L, {e1}L, {e2}L}};
    if (i < 0 || i > 2 || elems[i] == 0) return 0;
    if (!g_port[i]) g_port[i] = (float *)calloc(elems[i], sizeof(float));
    return g_port[i];
}}
{feeders}
"""

_GEMM_FEED = r"""
/* GemmSpace distribution: R={R} C={C}, per tile M/R={Mt} N/C={Nt}, sub-tiles
 * {tm}x{tn}, K chunk {kc}: m_rounds={mR} n_rounds={nR} k_rounds={kR}. */
static void fill_a(WspPort *p, long w, float *dst) {{
    long it = w / {kR}, kr = w % {kR}, mi = it / {nR};
    for (long i = 0; i < {tm}; i++)
        memcpy(dst + i * {kc}, g_port[0] + (p->r * {Mt} + mi * {tm} + i) * {K} + kr * {kc}, {kc} * sizeof(float));
}}
static void fill_b(WspPort *p, long w, float *dst) {{
    long it = w / {kR}, kr = w % {kR}, ni = it % {nR};
    for (long j = 0; j < {tn}; j++)
        memcpy(dst + j * {kc}, g_port[1] + (p->c * {Nt} + ni * {tn} + j) * {K} + kr * {kc}, {kc} * sizeof(float));
}}
static void drain_c(WspPort *p, long it, const float *src) {{
    long mi = it / {nR}, ni = it % {nR};
    for (long i = 0; i < {tm}; i++)
        memcpy(g_port[2] + (p->r * {Mt} + mi * {tm} + i) * {N} + p->c * {Nt} + ni * {tn}, src + i * {tn}, {tn} * sizeof(float));
}}
extern "C" int {sig}_run(void) {{
    for (int i = 0; i < 3; i++) if (!{sig}_port(i)) return -1;
    for (int r = 0; r < {R}; r++)
        for (int c = 0; c < {C}; c++) {{
            WspPort pa{{r, c, 0, std::vector<float>({tm} * {kc}), fill_a, 0}};
            WspPort pb{{r, c, 0, std::vector<float>({tn} * {kc}), fill_b, 0}};
            WspPort pc{{r, c, 0, std::vector<float>({tm} * {tn}), 0, drain_c}};
            input_window_int32 wa{{&pa}}, wb{{&pb}};
            output_window_int32 wc{{&pc}};
            {kernel_name}(&wa, &wb, &wc);
            if (pa.count != {nA} || pb.count != {nA} || pc.count != {nC}) {{
                fprintf(stderr, "{sig}: tile(%d,%d) window count A=%ld B=%ld C=%ld, DMA delivers %d/%d/%d\n",
                        r, c, pa.count, pb.count, pc.count, {nA}, {nA}, {nC});
                return -3;
            }}
        }}
    return 0;
}}
"""

_ROW_FEED = r"""
/* RowSpace distribution: R={R} tiles x {Rt} rows, {rpw} rows ({win} floats) per window. */
static void fill_row(WspPort *p, long w, float *dst, int port) {{
    memcpy(dst, g_port[port] + ((long)p->r * {Rt} + w * {rpw}) * {cols}, {win} * sizeof(float));
}}
static void fill_a(WspPort *p, long w, float *dst) {{ fill_row(p, w, dst, 0); }}
static void fill_b(WspPort *p, long w, float *dst) {{ {fill_b} }}
static void drain_c(WspPort *p, long w, const float *src) {{
    memcpy(g_port[2] + ((long)p->r * {Rt} + w * {rpw}) * {cols}, src, {win} * sizeof(float));
}}
extern "C" int {sig}_run(void) {{
    if (!{sig}_port(0) || !{sig}_port(2)) return -1;
    {need_b}
    for (int r = 0; r < {R}; r++) {{
        WspPort pa{{r, 0, 0, std::vector<float>({win}), fill_a, 0}};
        WspPort pb{{r, 0, 0, std::vector<float>({bwin}), fill_b, 0}};
        WspPort pc{{r, 0, 0, std::vector<float>({win}), 0, drain_c}};
        input_window_int32 wa{{&pa}}, wb{{&pb}};
        output_window_int32 wc{{&pc}};
        {call};
        if (pa.count != {nA} || pc.count != {nA} || pb.count != {nB}) {{
            fprintf(stderr, "{sig}: tile %d window count A=%ld B=%ld C=%ld, DMA delivers %d/%d/%d\n",
                    r, pa.count, pb.count, pc.count, {nA}, {nB}, {nA});
            return -3;
        }}
    }}
    return 0;
}}
"""


def emu_source(lib: dict, kernel_src: str, kernel_file: str = "") -> str:
    e = port_elems(lib)
    R, C = lib["mesh"]
    if lib["template"] == "row":
        R = C            # RowSpace: one tile per mesh column
    if lib["template"] == "gemm":
        Mt, Nt = lib["M"] // R, lib["N"] // C
        mR, nR, kR = Mt // TILE_M, Nt // TILE_N, lib["K"] // lib["kc"]
        feeders = _GEMM_FEED.format(sig=lib["sig"], R=R, C=C, Mt=Mt, Nt=Nt, tm=TILE_M, tn=TILE_N,
                                    kc=lib["kc"], mR=mR, nR=nR, kR=kR, K=lib["K"], N=lib["N"],
                                    nA=mR * nR * kR, nC=mR * nR, kernel_name=lib["kernel"])
    else:
        Rt, rpw, cols = lib["rows"] // R, lib["rpw"], lib["cols"]
        win = rpw * cols
        nA = Rt // rpw
        if lib["op"] == "layernorm":
            p = 2 * cols
            bwin = min(p, win)
            fill_b = f"memcpy(dst, g_port[1] + w * {bwin}, {bwin} * sizeof(float)); (void)p;"
            nB = p // bwin
        elif lib["ports"] == 3:
            bwin, nB = win, nA
            fill_b = "fill_row(p, w, dst, 1);"
        else:
            bwin, nB, fill_b = 1, 0, "(void)p; (void)w; (void)dst;"
        call = (f"{lib['kernel']}(&wa, &wb, &wc)" if lib["ports"] == 3
                else f"{lib['kernel']}(&wa, &wc)")
        feeders = _ROW_FEED.format(sig=lib["sig"], R=R, Rt=Rt, rpw=rpw, cols=cols, win=win,
                                   bwin=bwin, fill_b=fill_b, nA=nA, nB=nB, call=call,
                                   need_b=(f"if (!{lib['sig']}_port(1)) return -1;"
                                           if lib["ports"] == 3 else ""))
    return _HARNESS.format(sig=lib["sig"], kernel=kernel_src, kernel_file=kernel_file,
                           e0=e[0], e1=e[1], e2=e[2], feeders=feeders)


def build_emulators(libs: dict, results: dict, out_dir: Path, verbose: bool = True) -> list:
    """Compile one emulator object per built library. Returns the ``.o`` paths."""
    out_dir.mkdir(parents=True, exist_ok=True)
    objs = []
    for sig, lib in libs.items():
        res = results.get(sig, {})
        ksrc = Path(res.get("kernel_source", ""))
        if not res.get("ok") or not ksrc.is_file():
            raise RuntimeError(f"{sig}: no resolved kernel (library did not build)")
        src = out_dir / f"emu_{sig}.cc"
        obj = src.with_suffix(".o")
        text = emu_source(lib, ksrc.read_text(), str(ksrc))
        if not (obj.is_file() and src.is_file() and src.read_text() == text):
            src.write_text(text)
            subprocess.run(["g++", "-O3", "-fPIC", "-std=c++17", "-w", "-c", str(src), "-o", str(obj)],
                           check=True)
        objs.append(str(obj))
    if verbose:
        print(f"  [emu] {len(objs)} emulated libraries (resolved aiehlc kernels, x86) in {out_dir}")
    return objs
