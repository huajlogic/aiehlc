"""Emit the int8 ResNet-18 v2 oracle as plain C + a weight blob.

The generated C is a **transcription** of ``qresnet.QuantResNet18.forward`` —
same layer order, same integer arithmetic, same requantization — so the two can
be diffed numerically layer by layer. Anything the C computes differently from
the numpy oracle is a bug in this file, not a modelling choice.

Weights are emitted as a **binary blob**, not C array literals
----------------------------------------------------------------
ResNet-18 is 11.68 MB of int8 weights. As `int8_t w[] = {...}` that is roughly a
40 MB source file, which is slow to compile and, more importantly, makes the
per-layer offsets invisible. Instead the weights go to ``weights.bin`` and are
linked in with ``ld -r -b binary`` (the same mechanism the AIE flow already uses
to embed kernel ELFs into the host). The C reads them through a generated table
of offsets, so the layout is one place and checkable.

Where the C legitimately differs from the numpy oracle
------------------------------------------------------
The residual add. The oracle sums ``out_f + skip_f`` in float and quantizes the
result once; the C receives two int8 tensors and must rescale-and-round each
branch before summing (``q_add``). That is one extra rounding per branch per
block, compounded over 8 residual blocks, and it is inherent to an all-int8
dataflow rather than a defect — a float intermediate would mean the tensor
crossing that layer boundary is not int8.

Measured cost on the reference image: top-1 unchanged (Samoyed), confidence
89.1% -> 83.9%, top-5 membership shuffled below rank 1. Both remain 4/5 against
the float model. If that margin ever matters, the fix is to widen the residual
accumulator to int16 or int32 rather than to reintroduce float.

Fixed-point requantization
--------------------------
The numpy oracle keeps the requant multiplier as float32. Here it becomes an
int32 multiplier plus a right shift::

    M_real ≈ M_int / 2^shift        (M_int in [2^30, 2^31))
    out    = (acc * M_int + rounding) >> shift

chosen per output channel. ``emit_requant_params`` picks the largest shift that
keeps ``M_int`` inside int32, which maximizes retained precision. The C uses
int64 for the intermediate product — ``acc`` can approach 2^22 and ``M_int``
2^31, so int32 would overflow.

Layer config is int32, not int8
-------------------------------
The existing AIE path packs ``{H,W,Cin,Cout,K,stride}`` as int8 (ceiling 255);
real ResNet-18 has 512 channels and 1000 classes. This emitter therefore uses a
plain C struct with ``int`` fields rather than the packed int8 header.
"""

