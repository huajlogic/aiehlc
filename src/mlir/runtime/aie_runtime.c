/* Find the anchor slot for (col,row), creating it if new; NULL if the table is
 * full. */
static AieTraceAnchor *__aie_trace_anchor_slot(AieTraceProfile *p, uint8_t col, uint8_t row) {
    for (uint32_t i = 0; i < p->nanchor; i++) {
        if (p->anchor[i].col == col && p->anchor[i].row == row)
            return &p->anchor[i];
    }
    if (p->nanchor >= AIE_TRACE_ANCHOR_CAP)
        return NULL;
    AieTraceAnchor *a = &p->anchor[p->nanchor++];
    a->col = col;
    a->row = row;
    a->aie0 = 0;
    a->aie1 = 0;
    return a;
}

void __Runtime_aie_trace_profile_anchor(AieTraceProfile *p, int which, XAie_LocType tile, uint64_t aie, uint64_t host) {
    if (!p)
        return;
    AieTraceAnchor *a = __aie_trace_anchor_slot(p, tile.Col, tile.Row);
    if (a) {
        if (which == 0)
            a->aie0 = aie;
        else
            a->aie1 = aie;
    }
    if (which == 0)
        p->host0 = host;
    else
        p->host1 = host;
}

void __Runtime_aie_trace_profile_event(AieTraceProfile *p, int iter, const char *phase, uint64_t host) {
    if (!p)
        return;
    if (p->nevt >= AIE_TRACE_EVENT_CAP) {
        p->evt_dropped++;
        return;
    }
    AieTraceHostEvt *e = &p->evt[p->nevt++];
    e->iter = iter;
    e->phase = phase;
    e->host = host;
}

void __Runtime_aie_trace_profile_set_trace_words(AieTraceProfile *p, XAie_LocType tile, uint32_t nwords) {
    if (!p)
        return;
    p->words_col = tile.Col;
    p->words_row = tile.Row;
    p->nwords = nwords;
}

void __Runtime_aie_trace_profile_dump(AieTraceProfile *p) {
    if (!p) {
        printf("[aie_runtime] trace_profile_dump: NULL profile\n");
        return;
    }
    printf("[aie_runtime] trace_profile_dump: %u intervals (dropped=%u)\n", (unsigned)p->count, (unsigned)p->dropped);

    /* Host<->AIE time-sync block: only when something was recorded, so a
     * decode-only profile keeps emitting just the interval lines below. */
    if (p->cps)
        printf("[TIMESYNC] cps=%llu\n", (unsigned long long)p->cps);
    if (p->nanchor) {
        printf("[TIMESYNC] anchor0 host=%llu\n", (unsigned long long)p->host0);
        for (uint32_t i = 0; i < p->nanchor; i++)
            printf("[TIMESYNC] anchor0 tile=%u,%u aie=%llu\n", (unsigned)p->anchor[i].col, (unsigned)p->anchor[i].row,
                   (unsigned long long)p->anchor[i].aie0);
        printf("[TIMESYNC] anchor1 host=%llu\n", (unsigned long long)p->host1);
        for (uint32_t i = 0; i < p->nanchor; i++)
            printf("[TIMESYNC] anchor1 tile=%u,%u aie=%llu\n", (unsigned)p->anchor[i].col, (unsigned)p->anchor[i].row,
                   (unsigned long long)p->anchor[i].aie1);
    }
    for (uint32_t e = 0; e < p->nevt; e++)
        printf("[TIMESYNC] hostevt iter=%d phase=%s host=%llu\n", p->evt[e].iter,
               p->evt[e].phase ? p->evt[e].phase : "?", (unsigned long long)p->evt[e].host);
    /* Effective AIE Hz from the empirical slope (sanity only). */
    if (p->host1 > p->host0 && p->cps) {
        for (uint32_t i = 0; i < p->nanchor; i++)
            printf("[TIMESYNC] aiehz tile=%u,%u hz=%.3f\n", (unsigned)p->anchor[i].col, (unsigned)p->anchor[i].row,
                   (double)(p->anchor[i].aie1 - p->anchor[i].aie0) / (double)(p->host1 - p->host0) * (double)p->cps);
    }
    if (p->nwords)
        printf("[TIMESYNC] trace tile=%u,%u words=%u\n", (unsigned)p->words_col, (unsigned)p->words_row,
               (unsigned)p->nwords);

    /* Decoded AIE intervals, one machine-readable [TIMESYNC] trace line each. */
    for (uint32_t i = 0; i < p->count; i++) {
        AieTraceInterval *v = &p->iv[i];
        char names[128];
        __core_trace_names(v->mask, names, sizeof(names));
        if (v->start_cycle == v->end_cycle)
            printf("[TIMESYNC] trace tile=%u,%u %llu  %s\n", (unsigned)v->col, (unsigned)v->row,
                   (unsigned long long)v->start_cycle, names);
        else
            printf("[TIMESYNC] trace tile=%u,%u %llu -- %llu  %s  (%llu cyc)\n", (unsigned)v->col, (unsigned)v->row,
                   (unsigned long long)v->start_cycle, (unsigned long long)v->end_cycle, names,
                   (unsigned long long)(v->end_cycle - v->start_cycle + 1u));
    }
}

/* ---------------------------------------------------------------------------
 * Declarative core-trace session (#pragma aie_trace auto-injection).
 *
 * Fixed-reserved MemTile drain convention (v1). The core TRACE stream is routed
 * DOWN the column into the same-column top MemTile's S2MM DMA (see
 * __Runtime_core_trace_setup). Every armed tile needs a distinct triple of
 * (stream channel, MemTile S2MM channel, MemTile BD) plus a distinct MemTile
 * buffer region so multiple tiles in ONE column do not collide. We reserve a
 * small fixed band high in MemTile memory, away from the GEMM's own caching.
 *
 * The values mirror the hand-tuned, HW-validated constants in
 * example/perf/aieml_perf.cc:
 *   - setup uses the DMA-view address (TRC_MEMTILE_DMA_HI | region), read uses
 *     the plain region offset (the MemTile-loc DataMemBlockRead view).
 *   - MemTile DMA parity rule (aie_runtime.c core_trace_setup): even S2MM ch
 *     needs BD<24, odd ch needs BD>=24. Slot pairs below honour this.
 * ------------------------------------------------------------------------- */

#define AIE_TRACE_SESSION_CAP 16u     /* max tiles armed per run            */
#define AIE_TRACE_SLOTS_PER_COL 4u    /* strm_ch / S2MM ch range 0..3       */
#define AIE_TRACE_BUF_LEN 0x1000u     /* 4 KB raw trace words per tile      */
#define AIE_TRACE_REGION_BASE 0x8000u /* MemTile-loc read view base offset  */
#define AIE_TRACE_DMA_HI 0x80000u     /* OR'd in for the DMA-view (setup)   */

/* One armed tile and the drain resources reserved for it. */
typedef struct {
    uint8_t col, row;   /* compute tile, mesh/partition-relative              */
    uint8_t mt_row;     /* same-column top MemTile row (read loc)             */
    uint32_t read_addr; /* MemTile-loc read view offset                       */
    uint32_t len_bytes; /* trace buffer length                                */
} AieTraceSessionEntry;

static AieTraceSessionEntry s_trace_session[AIE_TRACE_SESSION_CAP];
static uint32_t s_trace_session_n = 0;
/* Per-column count of tiles armed so far, to hand out distinct slots. Indexed
 * by column; small fixed cap covers any realistic partition width. */
#define AIE_TRACE_MAX_COLS 64u
static uint8_t s_trace_col_used[AIE_TRACE_MAX_COLS];

void __Runtime_core_trace_begin_ch(XAie_DevInst *dev, uint8_t col, uint8_t row, uint8_t strm_ch_arg) {
    if (!dev) {
        printf("[aie_runtime] core_trace_begin: NULL dev, ignored\n");
        return;
    }
    /* Only compute (core) tiles carry a core trace unit. */
    if (row < XAIE_AIE_TILE_ROW_START) {
        printf("[aie_runtime] core_trace_begin: tile(%u,%u) is not a compute tile "
               "(row < %u); ignored\n",
               (unsigned)col, (unsigned)row, (unsigned)XAIE_AIE_TILE_ROW_START);
        return;
    }
    if (col >= AIE_TRACE_MAX_COLS) {
        printf("[aie_runtime] core_trace_begin: col %u out of range; ignored\n", (unsigned)col);
        return;
    }
    /* Idempotent: skip a repeated (col,row). */
    for (uint32_t i = 0; i < s_trace_session_n; i++) {
        if (s_trace_session[i].col == col && s_trace_session[i].row == row) {
            printf("[aie_runtime] core_trace_begin: tile(%u,%u) already armed; skipped\n", (unsigned)col,
                   (unsigned)row);
            return;
        }
    }
    if (s_trace_session_n >= AIE_TRACE_SESSION_CAP) {
        printf("[aie_runtime] core_trace_begin: session registry full (%u); tile(%u,%u) dropped\n",
               (unsigned)AIE_TRACE_SESSION_CAP, (unsigned)col, (unsigned)row);
        return;
    }
    uint8_t slot = s_trace_col_used[col];
    if (slot >= AIE_TRACE_SLOTS_PER_COL) {
        printf("[aie_runtime] core_trace_begin: column %u already has %u traced tiles "
               "(max %u S2MM/stream slots); tile(%u,%u) dropped\n",
               (unsigned)col, (unsigned)slot, (unsigned)AIE_TRACE_SLOTS_PER_COL, (unsigned)col, (unsigned)row);
        return;
    }

    /* Reserve this tile's drain resources by convention:
     *   strm_ch  : the physical stream channel (0..3) each hop of the core->MemTile
     *              route rides. AUTO = slot. A caller may PIN it to dodge a
     *              data-plane flow that shares this tile's SOUTH egress (the core
     *              trace route is programmed directly, outside the routing
     *              engine's resource manager, so a data DMA on the same SOUTH
     *              channel would deadlock — see aieml_perf.cc). Independent of
     *              s2mm_ch: the MemTile NORTH slave port strm_ch feeds DMA channel
     *              s2mm_ch, so the two channel numbers need not match.
     *   s2mm_ch  = slot: MemTile S2MM channel.
     *   bdnum    : parity-correct for the channel (even ch -> even BD<24,
     *              odd ch -> odd BD>=24). Use 4,25,6,27 for slots 0..3.
     *   region   : a distinct 4 KB window per slot, high in MemTile memory.
     */
    static const uint8_t k_bd_for_slot[AIE_TRACE_SLOTS_PER_COL] = {4u, 25u, 6u, 27u};
    uint8_t strm_ch = (strm_ch_arg == AIE_TRACE_STRM_CH_AUTO) ? slot : strm_ch_arg;
    if (strm_ch >= AIE_TRACE_SLOTS_PER_COL) {
        printf("[aie_runtime] core_trace_begin: strm_ch %u out of range (0..%u); tile(%u,%u) dropped\n",
               (unsigned)strm_ch, (unsigned)(AIE_TRACE_SLOTS_PER_COL - 1u), (unsigned)col, (unsigned)row);
        return;
    }
    uint8_t s2mm_ch = slot;
    uint8_t bdnum = k_bd_for_slot[slot];
    uint32_t read_addr = AIE_TRACE_REGION_BASE + (uint32_t)slot * AIE_TRACE_BUF_LEN;
    uint32_t setup_addr = read_addr | AIE_TRACE_DMA_HI;

    XAie_LocType tile = XAie_TileLoc(col, row);
    /* Pass the generated routing resource map when this flow has one so the trace
     * route's strm_ch/s2mm_ch/pkt id dodge the recorded data-plane ports; absent
     * (raw/single-kernel flow) -> NULL/0 keeps the convention values above. */
#ifdef AIE_HAVE_RESOURCE_MAP
    const struct AieResourceEntry *rm = __aie_resource_map;
    int rmn = __aie_resource_map_count;
#else
    const struct AieResourceEntry *rm = 0;
    int rmn = 0;
#endif
    AieRC rc = __Runtime_core_trace_setup(dev, tile, setup_addr, AIE_TRACE_BUF_LEN, strm_ch, s2mm_ch, bdnum, rm, rmn);
    if (rc != XAIE_OK) {
        printf("[aie_runtime] core_trace_begin: core_trace_setup failed rc=%d tile(%u,%u)\n", (int)rc, (unsigned)col,
               (unsigned)row);
        return;
    }

    AieTraceSessionEntry *e = &s_trace_session[s_trace_session_n++];
    e->col = col;
    e->row = row;
    e->mt_row = (uint8_t)(XAIE_AIE_TILE_ROW_START - 1); /* top memtile, same column */
    e->read_addr = read_addr;
    e->len_bytes = AIE_TRACE_BUF_LEN;
    s_trace_col_used[col] = (uint8_t)(slot + 1u);
    printf("[aie_runtime] core_trace_begin: armed tile(%u,%u) slot=%u strm_ch=%u s2mm_ch=%u bd=%u "
           "read_addr=0x%x\n",
           (unsigned)col, (unsigned)row, (unsigned)slot, (unsigned)strm_ch, (unsigned)s2mm_ch, (unsigned)bdnum,
           read_addr);
}

void __Runtime_core_trace_begin(XAie_DevInst *dev, uint8_t col, uint8_t row) {
    __Runtime_core_trace_begin_ch(dev, col, row, AIE_TRACE_STRM_CH_AUTO);
}

void __Runtime_core_trace_end_into(XAie_DevInst *dev, AieTraceProfile *prof) {
    if (s_trace_session_n == 0)
        return; /* nothing armed: clean no-op */
    if (!dev) {
        printf("[aie_runtime] core_trace_end: NULL dev; %u armed tiles not drained\n", (unsigned)s_trace_session_n);
        s_trace_session_n = 0;
        for (uint32_t c = 0; c < AIE_TRACE_MAX_COLS; c++)
            s_trace_col_used[c] = 0;
        return;
    }

    /* Read via the MemTile loc (same column, top memtile row). __Runtime_core_trace_read
     * dispatches on tile type, so a MemTile loc reads MemTile memory at read_addr. Decode
     * into the caller-supplied profile; the caller owns init and dump. */
    static uint32_t trc_buf[AIE_TRACE_BUF_LEN / 4u];
    for (uint32_t i = 0; i < s_trace_session_n; i++) {
        AieTraceSessionEntry *e = &s_trace_session[i];
        XAie_LocType mt = XAie_TileLoc(e->col, e->mt_row);
        XAie_LocType core = XAie_TileLoc(e->col, e->row);
        uint32_t words = e->len_bytes / 4u;
        if (words > (AIE_TRACE_BUF_LEN / 4u))
            words = AIE_TRACE_BUF_LEN / 4u;
        AieRC rc = __Runtime_core_trace_read(dev, mt, e->read_addr, trc_buf, words);
        if (rc != XAIE_OK) {
            printf("[aie_runtime] core_trace_end: core_trace_read failed rc=%d tile(%u,%u) memtile(%u,%u)\n", (int)rc,
                   (unsigned)e->col, (unsigned)e->row, (unsigned)e->col, (unsigned)e->mt_row);
            continue;
        }
        __Runtime_aie_trace_profile_attach(prof, core);
        __Runtime_core_trace_decode(trc_buf, words, prof);
        __Runtime_aie_trace_profile_set_trace_words(prof, core, words);
    }

    /* Clear the registry for a possible subsequent run in the same process. */
    s_trace_session_n = 0;
    for (uint32_t c = 0; c < AIE_TRACE_MAX_COLS; c++)
        s_trace_col_used[c] = 0;
}

void __Runtime_core_trace_end(XAie_DevInst *dev) {
    if (s_trace_session_n == 0)
        return; /* nothing armed: clean no-op */
    static AieTraceProfile trc_prof;
    __Runtime_aie_trace_profile_init(&trc_prof);
    __Runtime_core_trace_end_into(dev, &trc_prof);
    __Runtime_aie_trace_profile_dump(&trc_prof);
}

