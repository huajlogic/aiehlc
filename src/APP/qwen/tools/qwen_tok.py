"""Tokenizer helper for the qwen engine (the host side of a board run).

  qwen_tok.py <model_dir> encode "question" [--think] [--header out.h --ngen N]
  qwen_tok.py <model_dir> decode 1,2,3        (or a log: decode --log applog, reads the "GEN" / "QW GEN" line)
"""
import argparse, re, sys

from transformers import AutoTokenizer


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("model_dir")
    ap.add_argument("cmd", choices=("encode", "decode"))
    ap.add_argument("text", nargs="?")
    ap.add_argument("--think", action="store_true", help="chat template with thinking on (default off)")
    ap.add_argument("--raw", action="store_true", help="no chat template")
    ap.add_argument("--header", help="write qwen_prompt.h for the board app")
    ap.add_argument("--ngen", type=int, default=64)
    ap.add_argument("--log")
    a = ap.parse_args()
    tok = AutoTokenizer.from_pretrained(a.model_dir)
    if a.cmd == "encode":
        text = a.text if a.raw else tok.apply_chat_template(
            [{"role": "user", "content": a.text}], tokenize=False, add_generation_prompt=True,
            enable_thinking=a.think)
        ids = tok(text).input_ids
        print(",".join(map(str, ids)))
        if a.header:
            with open(a.header, "w") as f:
                f.write(f"/* generated by qwen_tok.py: {a.text!r} (thinking {'on' if a.think else 'off'}) */\n")
                f.write("static const int qw_prompt[] = {" + ",".join(map(str, ids)) + "};\n")
                f.write(f"#define QW_NGEN {a.ngen}\n")
        return
    src = a.text
    if a.log:
        m = re.findall(r"^(?:QW )?GEN((?: \d+)+)", open(a.log, errors="replace").read(), re.M)
        if not m:
            sys.exit("no GEN line in " + a.log)
        src = m[-1]
    ids = [int(t) for t in re.findall(r"\d+", src)]
    print(tok.decode(ids))


if __name__ == "__main__":
    main()
