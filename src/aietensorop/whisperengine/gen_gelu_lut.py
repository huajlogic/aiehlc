"""Write eng/we_gelu_lut.h: bf16(erf-GELU(x)) for every bf16 x with
1/8 <= |x| < 4 (biased exponent 124..128), in aie::lut<4, bfloat16> layout:
values in groups of 16 (256-bit bank width), each group stored twice; the
kernel keeps two such copies (ab, cd) in different banks.
Index = sign*640 + (exp-124)*128 + mantissa  (we_model.gelu_aie is the model)."""
import math
import struct
import sys
from pathlib import Path


def bf16_bits(f):
    u = struct.unpack("<I", struct.pack("<f", f))[0]
    u += 0x7FFF + ((u >> 16) & 1)
    return (u >> 16) & 0xFFFF


def table():
    vals = []
    for s in (0, 1):
        for e in range(124, 129):
            for m in range(128):
                x = struct.unpack("<f", struct.pack("<I", (s << 31) | (e << 23) | (m << 16)))[0]
                vals.append(bf16_bits(0.5 * x * (1.0 + math.erf(x / math.sqrt(2.0)))))
    return vals


def main(out):
    v = table()
    assert len(v) == 1280
    rep = []
    for g in range(0, len(v), 16):
        rep += v[g:g + 16] * 2
    lines = ["/* Generated by gen_gelu_lut.py -- do not edit. 1280 bf16 GELU values, 256-bit groups doubled. */",
             "#define WE_GELU_LUT_N 1280", "#define WE_GELU_LUT_INIT { \\"]
    for i in range(0, len(rep), 16):
        lines.append("    " + ", ".join(f"0x{x:04x}" for x in rep[i:i + 16]) + ", \\")
    lines.append("}")
    Path(out).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else str(Path(__file__).parent / "eng/we_gelu_lut.h"))
