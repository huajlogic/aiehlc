#!/usr/bin/env python3
"""P4a/P4 (sprint unet-board-apu-aie): the WHOLE bk-sdm-tiny UNet (unet_sim.onnx,
3 inputs) -> aiegraph.convert (fp32, branch aiegraph-unet-multiinput + the
2026-11-10 bias_add/residual fix) -> per-layer C -> A78 main.elf with the REAL
x86 inputs embedded (sample[1,4,32,32], timestep[1] as int32, ehs[1,77,768])
and Shuhua's p1_cos.c compare (ref_unet_out) linked in.

  $AGPY build_unet.py --onnx unet_sim.onnx --real-io <real_io> --aie none|conv --out <dir>

--aie none : every layer is TVM-generated C on the A78 (aie_launches=0). P4a.
--aie conv : the conv layers of --partition (p35/partition.json) run on the AIE
             (gemm_bf16 64x64x64 tiles, unet_aie.py); the rest is TVM C on the A78.
             Prints aie_launches_planned=<N> (== partition.json N).

timestep: the ONNX input is int64; the graph is rewritten so the input is int32
(real_io/timestep_i32.bin) followed by Cast(int32->int64) -- the A78 C runtime
then receives exactly the 4 bytes whose crc32 is part of unet_in.crc32.
"""
import argparse
import json
import os
import shutil
import sys
import zlib
from pathlib import Path

import numpy as np

# BSP lscript.ld reserves a 1 GiB heap in the 2 GiB DDR_LOW0; nothing here
# mallocs more than stdio buffers, and the 1.29 GB weights need the room.
# AIEHLC_SKIP_BSS_DEFAULT=1 is what aiehlc.sh --skip-bss adds; it is repeated here because
# aiegraph re-runs hostcompile.sh for the layer archive (aie_layer_lib) without aiehlc.sh
WARM_DEFS = "-DAIEHLC_ZFILL_WIDE=1 -DAIEHLC_PMLOAD_WIDE=1 -DAIEHLC_PM_WARM_SKIP=1 -DAIEHLC_SKIP_BSS_DEFAULT=1"
LAUNCH_OPTS_WARM = ("skip-bss+ZFILL_WIDE+PMLOAD_WIDE+PM_WARM_SKIP,core_reset_unreset_per_launch,"
                    "bd_warm_skip=off")
HEAP_LDFLAG = "-Wl,--defsym,_HEAP_SIZE=0x8000000"
P1_COS_C = Path(__file__).resolve().parent / "p1_cos.c"

MAIN_C = r"""/* main.c for the whole UNet on A78 -- generated by build_unet.py (do not edit).
 * Feeds the 3 real x86 inputs (unet_inputs.h, from real_io/) to the aiegraph/TVM
 * fp32 graph and compares the noise_pred with x86 ORT via p1_cmp(). */
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include "aie_timer.h"
#include "unet_inputs.h"
#include "p1_ref.h"

void  graph_init(const uint8_t *params_blob);
void *graph_input_k(int k);
const char *graph_input_name(int k);
int   graph_n_inputs(void);
float *graph_run(void);
int    graph_output_len(void);
int p1_cmp(const char *tag, const float *got, const char *dtype, int aie_launches,
           int coreen_calls, int run_rc, double aie_flop_frac);
extern const uint8_t _binary_weights_bin_start[];
extern unsigned long __malloc_max_sbrked_mem; /* newlib, B symbol */
extern char _heap_start[], _heap_end[];

static uint32_t crc32_upd(uint32_t c, const uint8_t *p, unsigned long n) {
    for (unsigned long i = 0; i < n; ++i) {
        c ^= p[i];
        for (int k = 0; k < 8; ++k) c = (c >> 1) ^ (0xEDB88320u & (0u - (c & 1u)));
    }
    return c;
}

int main(void) {
    XTime t0, t1;
    char crc[16];
    printf("unet-%s: init (aiegraph fp32 C on A78, weights=%s, aie=%s)\n", UNET_AIE_MODE, UNET_WDTYPE, UNET_AIE_MODE);
    graph_init(_binary_weights_bin_start);
    if (graph_n_inputs() != UNET_N_INPUTS) {
        printf("unet: graph has %d inputs, expected %d\n", graph_n_inputs(), UNET_N_INPUTS);
        return 1;
    }
    /* copy each real input into the graph's own buffer, then crc those bytes */
    uint32_t c = 0xFFFFFFFFu;
    for (int k = 0; k < UNET_N_INPUTS; ++k) {
        if (strcmp(graph_input_name(k), unet_in_name[k]) != 0) {
            printf("unet: graph input %d is %s, expected %s\n", k, graph_input_name(k), unet_in_name[k]);
            return 1;
        }
        uint8_t *dst = (uint8_t *)graph_input_k(k);
        memcpy(dst, unet_in_ptr[k], unet_in_bytes[k]);
        c = crc32_upd(c, dst, unet_in_bytes[k]);
        printf("INPUT unet %s bytes=%lu\n", unet_in_name[k], unet_in_bytes[k]);
    }
    snprintf(crc, sizeof crc, "%08x", (unsigned)(c ^ 0xFFFFFFFFu));
    printf("INPUT unet sample+timestep_i32+ehs in_crc32_board=%s expect=%s %s (timestep=%d)\n",
           crc, P1_UNET_IN_CRC32, strcmp(crc, P1_UNET_IN_CRC32) == 0 ? "MATCH" : "MISMATCH",
           (int)unet_timestep[0]);
    if (strcmp(crc, P1_UNET_IN_CRC32) != 0) {
        printf("unet: input crc mismatch -- not comparing\n");
        return 1;
    }
    XTime_GetTime(&t0);
    float *out = graph_run();
    XTime_GetTime(&t1);
    int n = graph_output_len();
    printf("unet: graph_run %.3f ms, output elems=%d (ref %d)\n",
           1000.0 * (double)(t1 - t0) / (double)COUNTS_PER_SECOND, n, REF_UNET_OUT_N);
    if (n != REF_UNET_OUT_N) {
        printf("unet: output length mismatch\n");
        return 1;
    }
    printf("HEAP max_sbrked=%lu heap=%lu\n", (unsigned long)__malloc_max_sbrked_mem,
           (unsigned long)(_heap_end - _heap_start));
    int rc = p1_cmp("unet-" UNET_AIE_MODE, out, UNET_WDTYPE "w/" UNET_AIE_MODE, 0, 0, 0, 0.0);
    printf("device_teardown done\n");
    return rc;
}
"""


def log(msg):
    print(f"[build_unet] {msg}", flush=True)


def c_array(ctype, name, vals, fmt):
    body = ",\n".join(", ".join(fmt(v) for v in vals[i:i + 8]) for i in range(0, len(vals), 8))
    return f"static const {ctype} {name}[{len(vals)}] __attribute__((aligned(64))) = {{\n{body}\n}};\n"


def write_inputs_header(real_io: Path, path: Path, aie: str, wdtype: str = "fp32") -> str:
    s = np.fromfile(real_io / "sample.bin", dtype="<f4")
    t = np.fromfile(real_io / "timestep_i32.bin", dtype="<i4")
    e = np.fromfile(real_io / "ehs.bin", dtype="<f4")
    assert s.size == 4 * 32 * 32 and t.size == 1 and e.size == 77 * 768, (s.size, t.size, e.size)
    t64 = np.fromfile(real_io / "timestep_i64.bin", dtype="<i8")
    assert int(t64[0]) == int(t[0]), (t64, t)
    crc = "%08x" % zlib.crc32(s.tobytes() + t.tobytes() + e.tobytes())
    want = (real_io / "unet_in.crc32").read_text().strip()
    assert crc == want, (crc, want)
    f = lambda v: repr(float(v)) + "f" if np.isfinite(v) else "0.0f"
    hx = lambda v: "%.9ef" % float(v)
    txt = ["/* generated by build_unet.py from %s -- do not edit */" % real_io,
           "#pragma once", "#include <stdint.h>",
           '#define UNET_AIE_MODE "%s"' % aie, '#define UNET_WDTYPE "%s"' % wdtype,
           "#define UNET_N_INPUTS 3",
           c_array("float", "unet_sample", s, hx),
           c_array("int32_t", "unet_timestep", t, lambda v: "%d" % int(v)),
           c_array("float", "unet_ehs", e, hx),
           'static const char *const unet_in_name[3] = {"sample", "timestep", "encoder_hidden_states"};',
           "static const void *const unet_in_ptr[3] = {unet_sample, unet_timestep, unet_ehs};",
           "static const unsigned long unet_in_bytes[3] = {%d, %d, %d};"
           % (s.nbytes, t.nbytes, e.nbytes), ""]
    path.write_text("\n".join(txt))
    # the header must round-trip bit-exactly
    log(f"inputs: sample {s.size} f32, timestep {int(t[0])} i32, ehs {e.size} f32; "
        f"crc32(sample+t_i32+ehs)={crc} == unet_in.crc32")
    return crc


def timestep_to_i32(src: Path, dst: Path) -> Path:
    """Rewrite input 'timestep' int64 -> int32 + Cast(to int64) feeding the old consumers."""
    import onnx
    from onnx import TensorProto, helper
    if dst.is_file() and dst.stat().st_mtime > src.stat().st_mtime:
        log(f"reuse {dst}")
        return dst
    m = onnx.load(str(src))
    inp = next(i for i in m.graph.input if i.name == "timestep")
    assert inp.type.tensor_type.elem_type == TensorProto.INT64, inp
    inp.type.tensor_type.elem_type = TensorProto.INT32
    for n in m.graph.node:
        n.input[:] = ["timestep_i64" if x == "timestep" else x for x in n.input]
    m.graph.node.insert(0, helper.make_node("Cast", ["timestep"], ["timestep_i64"],
                                            to=TensorProto.INT64, name="timestep_i32_to_i64"))
    onnx.checker.check_model(m) if m.ByteSize() < 2**31 - 1 else None
    tmp = dst.with_suffix(".tmp.onnx")
    onnx.save(m, str(tmp))
    tmp.replace(dst)
    log(f"timestep int64 -> int32 input + Cast: {dst} ({dst.stat().st_size:,} B)")
    return dst


def aie_conv(a, emod, out: Path, hdr: Path):
    """--aie conv: map partition layers, build the AIE archive on a carrier layer,
    patch every partition call site in graph_driver.c. Returns (main.c, n_sites)."""
    import aiegraph._env as env
    env.frontend("")
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import unet_aie as ua
    import frontend.tvmrelay.arm_build as ab
    import frontend.tvmrelay.aiekernel.flow as flow
    part = json.loads(a.partition.resolve().read_text())
    work = Path(emod.workdir)
    sel, convs = ua.map_layers(a.onnx.resolve(), part, work, ab.param_offsets)
    planned = sum(c["launches"] for c in sel)
    if planned != int(part["N"]):
        raise SystemExit(f"planned launches {planned} != partition.json N {part['N']}")
    log(f"aie_launches_planned={planned} (partition.json N={part['N']}, {len(sel)} conv layers, "
        f"{sum(c['macs'] for c in sel)} MACs of {part['total_gemm_macs']} GEMM MACs)")
    for c in sel:
        log(f"  aie conv {c['cid']:2d} {c['onnx']} -> node {c['node']} {c['func']} "
            f"M={c['M']} N={c['N']} K={c['K']} s={c['sh']} p={c['ph']} launches={c['launches']}")
    ua.check_data_arg0(work / "layers", sel)
    lidx, car = ua.pick_carrier(sel, convs, work / "layers")
    log(f"carrier layer {lidx} ({car['func']}): aiegraph offload builds the gemm_bf16 archive on it")
    p = emod.offload_prototype(lidx, entry=ua.ENTRY)
    kcc = ua.write_kernel(out / "aiek_src", p.spec(), max(c["M"] * c["N"] for c in sel),
                          warm=(a.launch_opt == "warm"))
    log(f"kernel source {kcc}")

    # calibrate/emulate would run the whole UNet twice on x86; force=True ignores their
    # verdicts anyway -- skipped (the board run is the check).
    flow._calibrate = lambda net, plans, verbose: log("offload: calibrate skipped (UNet)")
    flow._emulate = lambda net, plans, verbose: log("offload: emulate skipped (UNet)")
    orig = getattr(ab.generate_driver, "_p35w_orig", ab.generate_driver)

    def generate_driver(graph_path, params_path, out_dir, *args, **kw):
        r = orig(graph_path, params_path, out_dir, *args, **kw)
        f = Path(out_dir) / "graph_driver.c"
        t, n = ua.patch_driver(f.read_text(), sel)
        f.write_text(t)
        log(f"graph_driver.c: {n} partition call sites -> unet_aie_conv")
        return r
    generate_driver._p35w_orig = orig
    ab.generate_driver = generate_driver

    rep = emod.offload(f"layer{lidx}", str(kcc), force=True, verbose=a.verbose)
    log(f"offload: {rep}")
    lp = json.loads((work / "layers" / "partition.json").read_text())
    if not any(L.get("target") == "aie" and L.get("archive") for L in lp["layers"]):
        raise SystemExit("offload FAILED: carrier layer has no AIE archive in layers/partition.json")
    if a.launch_opt == "warm":
        with open(hdr, "a") as f:
            f.write('#define UNET_LAUNCH_WARM 1\n#define UNET_LAUNCH_OPTS "%s"\n' % LAUNCH_OPTS_WARM)
    with open(hdr, "a") as f:
        f.write("#define UNET_AIE_PLANNED_LAUNCHES %d\n#define UNET_AIE_PLANNED_CALLS %d\n"
                "#define UNET_TOTAL_GEMM_MACS %dULL\n" % (planned, len(sel), int(part["total_gemm_macs"])))
    return ua.main_c(MAIN_C), len(sel)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--onnx", required=True, type=Path)
    ap.add_argument("--real-io", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--aie", choices=("none", "conv"), default="none")
    ap.add_argument("--wdtype", choices=("fp32", "bf16"), default="fp32",
                    help="bf16: weights.bin holds bf16 (RNE); each APU call expands its "
                         "weights into one static .bss fp32 scratch (~118 MB)")
    ap.add_argument("--partition", type=Path, default=None,
                    help="--aie conv: p35/partition.json (layers on the AIE, planned N)")
    ap.add_argument("--launch-opt", choices=("cold", "warm"), default="cold",
                    help="warm (P5): aiehlc --skip-bss + ZFILL_WIDE/PMLOAD_WIDE/PM_WARM_SKIP: the conv "
                         "kernel is loaded once, later launches only reset the cores (CoreReset+Unreset), "
                         "rewrite .data/BDs/locks, enable and wait")
    ap.add_argument("--verbose", action="store_true")
    a = ap.parse_args(argv)
    if a.aie == "conv":
        if a.partition is None or a.wdtype != "bf16":
            log("--aie conv needs --partition <partition.json> and --wdtype bf16")
            return 2
        # PH_COREEN is counted only by a runtime built with -DAIEHLC_PROFILING=1 (as P2/P3)
        os.environ["AIEHLC_PROFILING"] = "1"
        os.environ["EXTRA_DEFS"] = (os.environ.get("EXTRA_DEFS", "") + " -DAIEHLC_PROFILING=1").strip()
    if a.launch_opt == "warm":
        if a.aie != "conv":
            log("--launch-opt warm needs --aie conv")
            return 2
        # --skip-bss is safe for gemm_bf16: its .bss is the 6 DMA port buffers (filled by DMA /
        # written by the kernel before any read), aiehlc_cur_a/b/c (block cursors, only feed
        # klog, compiled out) and softfloat's float_rounding_mode (read by float32_add/mul,
        # never written) -- the kernel zeroes the latter on every launch (unet_aie.SOFTFLOAT_RM).
        os.environ["AIEHLC_SH_ARGS"] = "--skip-bss"
        os.environ["EXTRA_DEFS"] = (os.environ["EXTRA_DEFS"] + " " + WARM_DEFS).strip()
        log(f"launch_opt=warm defs={os.environ['EXTRA_DEFS']} aiehlc.sh={os.environ['AIEHLC_SH_ARGS']} "
            f"(AIEHLC_BD_WARM_SKIP not added: no Amit hardware ack in the channel)")
    out = a.out.resolve()
    real_io = a.real_io.resolve()
    out.mkdir(parents=True, exist_ok=True)

    # the gate runs plain $AGPY (no PYTHONPATH): use this checkout's aiegraph
    mi = Path(__file__).resolve().parents[3] / "src"
    if mi.is_dir() and str(mi) not in sys.path:
        sys.path.insert(0, str(mi))
    import aiegraph as ag
    root = Path(ag.__file__).resolve().parents[2]
    os.environ.setdefault("AIEHLC_ROOT", str(root))
    # 1.29 GB fp32 weights: read in place from the linked blob (no 2nd .bss copy)
    os.environ["AIEGRAPH_PARAMS_INPLACE"] = "1"
    os.environ["AIEGRAPH_WDTYPE"] = a.wdtype
    log(f"aiegraph from {ag.__file__} (repo {root})")

    hdr = out / "unet_inputs.h"
    write_inputs_header(real_io, hdr, a.aie, a.wdtype)

    onnx_i32 = timestep_to_i32(a.onnx.resolve(), out / "unet_sim_t32.onnx")
    m = ag.load(str(onnx_i32))
    log(f"loaded {m.name}: inputs {m.input_shapes} -> {m.output_shape}, "
        f"{sum(m.ops.values())} nodes {m.ops}")
    emod = m.convert(target="a78", quantize="fp32", image=str(real_io / "sample.bin"),
                     workdir=out / "ag_work", force=True, verbose=a.verbose)
    log(f"converted -> {emod.workdir} ({emod.state.get('layer_count') if hasattr(emod, 'state') else '?'} layers)")
    if not shutil.which("aarch64-none-elf-gcc"):
        # the gate runs plain $AGPY: take the cross toolchain from the repo setup
        import subprocess
        env = subprocess.run(["bash", "-c", f"cd {root} && source script/setup.sh "
                              "--path-set-only >/dev/null 2>&1; env -0"],
                             capture_output=True, check=True).stdout.decode()
        os.environ.update(kv.split("=", 1) for kv in env.split("\0") if "=" in kv)
        log(f"toolchain via {root}/script/setup.sh: {shutil.which('aarch64-none-elf-gcc')}")
    main_c = MAIN_C
    if a.aie == "conv":
        main_c, n_patched = aie_conv(a, emod, out, hdr)

    rep = emod.build(target="a78", verbose=a.verbose, main_c=main_c,
                     extra_sources=[P1_COS_C, real_io / "p1_ref.h", hdr],
                     extra_cflags="-DP1_COS_NO_MAIN " + HEAP_LDFLAG)
    if not rep.ok:
        log(f"build FAILED: {rep.reason}")
        return 1
    if a.aie == "conv":
        drv = (Path(rep.elf).parent / "graph_driver.c").read_text()
        got = drv.count("    unet_aie_conv(")
        if got != n_patched:
            log(f"build FAILED: linked driver has {got} unet_aie_conv call sites, expected {n_patched}")
            return 1
        log(f"linked driver: {got} call sites -> unet_aie_conv (AIE), weights of those read as bf16 in place")
    elf = out / "main.elf"
    shutil.copy2(rep.elf, elf)
    wb = Path(rep.elf).parent / "weights.bin"
    if wb.is_file():   # the blob netload streams to the board, beside the ELF
        shutil.copy2(wb, out / "weights.bin")
    log(f"built {rep.elf} -> {elf} ({elf.stat().st_size:,} B; weights.bin "
        f"{wb.stat().st_size if wb.is_file() else -1:,} B)")
    return 0


if __name__ == "__main__":
    try:
        rc = main()
    except Exception:
        import traceback
        traceback.print_exc()
        rc = 1
    print(f"GATE_RC={rc}", flush=True)
    sys.exit(rc)
